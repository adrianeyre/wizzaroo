/**
 * The Piper voice models Read it to me speaks with (ADR 0062): every voice on
 * Bryce Beattie's page, https://brycebeattie.com/files/tts/, pinned by size
 * and SHA-256. The server's `download-voices` command fetches each file from
 * the page's own bucket and refuses one that doesn't match; the app serves
 * them from its own origin, and a device keeps each one it has used.
 *
 * Shared by the client (which lists the voices) and the server (which serves
 * them), so it lives beside the curriculum both already import.
 */

export const piperVoiceSource = "https://sfo3.digitaloceanspaces.com/bkmdls/";

export type PiperVoiceLicence = "public-domain" | "jenny" | "cc-by-4";

export interface PiperFile {
  name: string;
  bytes: number;
  sha256: string;
}

export interface PiperModel {
  id: string;
  /** What the voice is called on the page. */
  label: string;
  description: string;
  accent: string;
  /** Female or male for a one-speaker model; a many-speaker model has both. */
  voice?: "female" | "male";
  licence: PiperVoiceLicence;
  model: PiperFile;
  config: PiperFile;
  /** Each reader's name, and the number Piper knows them by, in a many-speaker model. */
  speakers?: readonly (readonly [name: string, speakerId: number])[];
}

